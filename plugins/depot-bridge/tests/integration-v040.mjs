import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {handleRpc} from '../server/standalone-mcp.mjs';
import {selectAsset,platformSpec,locateCli,installationLocation} from '../server/installer.mjs';
import {seal,unseal,nonSecretReceipt,writeVault,readVault,saveReceipt,commitReceipt} from '../server/portable-vault.mjs';

const scratch=fs.mkdtempSync(path.join(os.tmpdir(),'qumi-depot-040-'));
const before={...process.env};
try{
 process.env.QUMI_PORTABLE_VAULT_FILE=path.join(scratch,'secure','vault.aes256gcm.json');
 process.env.QUMI_PROJECT_ROOT=path.join(scratch,'project');
 fs.mkdirSync(path.join(process.env.QUMI_PROJECT_ROOT,'.git'),{recursive:true});
 const spec=platformSpec();
 const assetName=`depot_2.1.2_${spec.os}_${spec.arch}.${spec.archiveExt}`;
 const digest='a'.repeat(64);
 const asset=selectAsset({tag_name:'v2.1.2',assets:[{name:assetName,digest:`sha256:${digest}`,size:100,browser_download_url:`https://github.com/depot/cli/releases/download/v2.1.2/${assetName}`}]});
 assert.equal(asset.sha256,digest);
 assert.match(installationLocation('project'),/\.qumi-tools/);
 assert.equal(locateCli().platform.os,spec.os);
 assert.throws(()=>selectAsset({tag_name:'v2.1.2',assets:[{name:assetName,size:100,browser_download_url:'https://evil.example/file'}]}),/SHA-256/);
 const encrypted=seal({DEPOT_TOKEN:'nonprod-sample-api-key-not-real',DEPOT_GIT_KEY:'nonprod-sample-git-key-not-real'},'correct-horse-battery-staple');
 const plaintext=unseal(encrypted,'correct-horse-battery-staple');
 assert.equal(plaintext.DEPOT_TOKEN,'nonprod-sample-api-key-not-real');
 assert.throws(()=>unseal(encrypted,'wrong-wrong-wrong'),/authenticate|decrypt|Unsupported state/i);
 writeVault(encrypted);assert.ok(readVault());
 const receipt=nonSecretReceipt(encrypted,{action:'rotate',changedKeys:['DEPOT_GIT_KEY']});
 const stored=saveReceipt(receipt);assert.ok(fs.existsSync(stored));
 assert.equal(JSON.stringify(receipt).includes('nonprod-sample'),false);
 assert.equal(JSON.stringify(encrypted).includes('nonprod-sample'),false);
 let msg=await handleRpc({jsonrpc:'2.0',id:1,method:'initialize',params:{protocolVersion:'2025-06-18'}});
 assert.equal(msg.result.serverInfo.version,'1.0.0-rc');
 msg=await handleRpc({jsonrpc:'2.0',id:2,method:'tools/list'});
 const names=new Set(msg.result.tools.map(t=>t.name));
 for(const name of ['health','list_builds','get_build','get_build_steps','get_build_step_logs','depot_cli_detect','depot_cli_install_plan','depot_cli_install','credential_request','git_askpass_status'])assert.ok(names.has(name),name);
 msg=await handleRpc({jsonrpc:'2.0',id:3,method:'tools/call',params:{name:'credential_request',arguments:{credential:'DEPOT_GIT_KEY'}}});
 assert.equal(msg.result.structuredContent.result.status,'operator_input_required');
 assert.equal(JSON.stringify(msg).includes('nonprod-sample'),false);
 msg=await handleRpc({jsonrpc:'2.0',id:4,method:'tools/call',params:{name:'depot_cli_install',arguments:{plan_id:'mock-plan',approved:true}}});
 assert.equal(msg.result.isError,true);assert.match(msg.result.content[0].text,/host policy/i);
 msg=await handleRpc({jsonrpc:'2.0',id:5,method:'tools/call',params:{name:'runtime_status',arguments:{}}});
 assert.equal(msg.result.structuredContent.result.mcpTransport.includes('stdio'),true);
 // Git receipt commits contain no vault or raw secret and stage only their own evidence file.
 const repo=path.join(scratch,'git-project');fs.mkdirSync(repo);
 execFileSync('git',['init','-q'],{cwd:repo});
 execFileSync('git',['config','user.email','qumi-test@example.invalid'],{cwd:repo});
 execFileSync('git',['config','user.name','QUMI test'],{cwd:repo});
 fs.writeFileSync(path.join(repo,'README.md'),'fixture\n');
 execFileSync('git',['add','README.md'],{cwd:repo});execFileSync('git',['commit','-qm','fixture'],{cwd:repo});
 const committed=commitReceipt(receipt,{repoRoot:repo,confirmed:true});
 assert.equal(committed.committed,true);assert.equal(committed.secret_material_committed,false);
 const namesGit=execFileSync('git',['show','--format=','--name-only','HEAD'],{cwd:repo,encoding:'utf8'}).trim();
 assert.match(namesGit,/evidence\/depot\/credential-rotations/);
 const gitContents=execFileSync('git',['show','HEAD:'+namesGit],{cwd:repo,encoding:'utf8'});
 assert.equal(gitContents.includes('nonprod-sample'),false);
 console.log('PASS: zero-dependency MCP registry, portable CLI assets, encrypted vault, safe rotation receipt and scoped Git commit');
}finally{
 for(const key of Object.keys(process.env))if(before[key]===undefined)delete process.env[key];
 Object.assign(process.env,before);fs.rmSync(scratch,{recursive:true,force:true});
}
