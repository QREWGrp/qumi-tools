import assert from 'node:assert/strict';import fs from 'node:fs';import os from 'node:os';import path from 'node:path';
import {encryptVault,decryptVault,receiptFor,saveVault,getProviderConfig,configStatus} from '../server/config.mjs';
import {risk,approveRecord,consumeApproval} from '../server/policy.mjs';
const base=fs.mkdtempSync(path.join(os.tmpdir(),'qumi-ionos-smoke-'));
process.env.QUMI_IONOS_CONFIG_DIR=base;
process.env.QUMI_IONOS_ALLOW_TEST_HTTP='1';process.env.NODE_ENV='test';
const secret='FAKE_TEST_IONOS_PAT_NEVER_REAL_123456789',pass='TEST_PASS_123456789';
const vault=encryptVault('ionos','http://127.0.0.1:1234/mcp',secret,pass);
assert(!JSON.stringify(vault).includes(secret));
const file=saveVault(vault);assert.equal(fs.statSync(file).mode & 0o777,0o600);
assert.equal(decryptVault(vault,pass).token,secret);
assert(!JSON.stringify(receiptFor(vault)).includes(secret));
process.env.QUMI_IONOS_VAULT_PASSPHRASE=pass;
assert.equal(getProviderConfig('ionos').token,secret);
assert.equal(configStatus().ionos.configured,true);
assert.equal(risk({name:'dns_get_zones'}),'read');
assert.equal(risk({name:'domains_update_auth_code'}),'change');
const args={zone_id:'z1',records:[{type:'A',name:'test.example',content:'198.51.100.2'}]};
const approval=approveRecord({provider:'ionos',tool:'dns_create_records',args});
assert.equal(consumeApproval(approval.id,'ionos','dns_create_records',args),true);
assert.throws(()=>consumeApproval(approval.id,'ionos','dns_create_records',args));
fs.rmSync(base,{recursive:true,force:true});
console.log('PASS encrypted credential roundtrip, redaction, risk classification, one-time exact-argument approvals');
